"""The SYNTHETIC workbooks: reproducible, flagged, and read like IonVantage files (SPEC section 0, decision 4).

These tests check the reader and the generator only. They make no claim about
BSU numbers.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path
import tomllib

import numpy as np
import pytest

from rawtims.model import FORMAT_IONVANTAGE_XLS
from rawtims.readers import sniff
from reader_fixtures import FIXTURES, SYNTHETIC, SYNTHETIC_PB, SYNTHETIC_U, read

ROOT = Path(__file__).resolve().parents[1]


def _generator():
    spec = importlib.util.spec_from_file_location("make_synthetic_fixtures", ROOT / "scripts" / "make_synthetic_fixtures.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_generator_reproduces_the_committed_files_byte_for_byte(tmp_path):
    written = _generator().write_all(tmp_path)
    assert sorted(p.name for p in written) == sorted(p.name for p in SYNTHETIC.iterdir())
    for path in written:
        assert path.read_bytes() == (SYNTHETIC / path.name).read_bytes(), path.name


def test_manifest_flags_them_synthetic():
    entries = {entry["path"]: entry for entry in tomllib.loads((FIXTURES / "MANIFEST.toml").read_text(encoding="utf-8"))["file"]}
    for path in (SYNTHETIC_U, SYNTHETIC_PB):
        entry = entries[path.relative_to(FIXTURES).as_posix()]
        assert entry["synthetic"] is True and "synthetic" in path.name
        assert entry["source"] == "generated by scripts/make_synthetic_fixtures.py"
    assert not any(entry["synthetic"] for key, entry in entries.items() if not key.startswith("synthetic/"))


@pytest.mark.parametrize("path", [SYNTHETIC_U, SYNTHETIC_PB], ids=lambda p: p.stem)
def test_marked_synthetic_inside_the_file(path):
    assert sniff(path).format == FORMAT_IONVANTAGE_XLS
    run = read(path)
    assert "SYNTHETIC" in run.metadata.sample_id and "SYNTHETIC" in run.metadata.method
    assert "SYNTHETIC" in run.metadata.extra["Synthetic Note"] and "not instrument data" in run.metadata.extra["Synthetic Note"]


def test_bsu_u_oxide_workbook():
    run = read(SYNTHETIC_U)
    meta = run.metadata
    assert run.element == "U"
    assert (meta.blocks, meta.cycles_per_block, run.n_cycles, run.blocks_measured, meta.aborted) == (12, 10, 120, 12, False)
    assert meta.complete is True and meta.stopped_early is False
    assert run.names == ["265 F", "267 F", "270 F", "270/267", "265/267", "272/270",
                         "238/235 oxide R18 0.00206", "233/235 oxide R18 0.00206", "238/233 oxide"]
    oxide = run.function("238/235 oxide R18 0.00206")
    assert oxide.is_ratio and oxide.metadata["oxide_r18"] == 0.00206 and oxide.metadata["oxide_corrected"]
    assert run.function("238/233 oxide").metadata == {"source_column": 10, "oxide_corrected": True}
    assert run.function("265 F").unit == "V" and run.function("265 F").collector == "F"
    # The generator's oxide columns follow the ET_Redux form from the raw ratios (r18 = 0.00206).
    r265, r270 = run.column("265/267"), run.column("270/267")
    factor = 1 - 2 * 0.00206 * r265
    np.testing.assert_allclose(run.column("238/235 oxide R18 0.00206"), r270 / factor, rtol=1e-14)
    np.testing.assert_allclose(run.column("233/235 oxide R18 0.00206"), r265 / factor, rtol=1e-14)
    assert 0.34 < np.median(run.column("238/235 oxide R18 0.00206")) < 0.47
    assert np.median(run.column("233/235 oxide R18 0.00206")) == pytest.approx(1.005, rel=1e-3)
    assert not run.invalid.any()


def test_et2535_pb_workbook():
    run = read(SYNTHETIC_PB)
    meta = run.metadata
    assert run.element == "Pb"
    assert meta.extra["beam_interpolation"] is True and meta.extra["cycles_per_block_method"] == 15
    assert (meta.blocks, meta.cycles_per_block, run.n_cycles, run.blocks_measured, meta.aborted) == (10, 16, 160, 10, False)
    assert meta.complete is True and meta.stopped_early is False
    assert {"202/205 D", "202 D", "206/204 D", "204/205 D"} <= set(run.names)
    assert run.keys.count("Daly/Faraday Gain #2") == 1
    assert run.function("202/205 D").collector == "D"
    assert np.median(run.column("202/205 D")) == pytest.approx(1.007, rel=1e-3)
    assert 240 < np.median(run.column("206/204 D")) < 9000
    planted = run.column("206/204 D")[run.cycle == 23][0]
    assert planted < 0.85 * np.median(run.column("206/204 D"))
    assert run.metadata.analysis_start is not None
