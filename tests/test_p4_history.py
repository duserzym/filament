def test_folder_changed_during_read_and_same_signature_tamper(tmp_path, monkeypatch):
    _, files = specimens(tmp_path / "synthetic-folder")
    folder = CompletedFolder(files[0].parent)
    settled(folder)
    import os

    stat = files[0].stat()
    data = files[0].read_bytes()
    files[0].write_bytes(data.replace(b"Version", b"version"))
    os.utime(files[0], ns=(stat.st_atime_ns, stat.st_mtime_ns))
    with pytest.raises(UnsupportedFile, match="content changed"):
        folder.snapshot_bytes(completed=True)
    files[0].write_bytes(data)
    folder.refresh(now=20)
    original = Path.read_bytes

    def changed(path):
        result = original(path)
        if path == files[0]:
            files[1].write_bytes(original(files[1]) + b"\n")
        return result

    monkeypatch.setattr(Path, "read_bytes", changed)
    assert not folder.refresh(now=21.1) and "changed during Refresh" in folder.notice


