@pytest.mark.parametrize(
    "case", ["mixed-header", "incomplete-block", "zero-cycle", "symlink"]
)
def test_folder_refuses_unverified_acquisition_shapes(tmp_path, case):
    """OGTripoli/source/vendors_data/IonVantageLiveDataCyclesFolder.cs:139-184.
    Synthetic conservative guards against silently padding or mixing acquisitions.
    """
    _, files = specimens(tmp_path / "synthetic-folder")
    folder = CompletedFolder(files[0].parent)
    if case == "mixed-header":
        files[1].write_bytes(
            files[1].read_bytes().replace(b"Synthetic z1", b"Other z1")
        )
    elif case == "incomplete-block":
        files[-1].unlink()
    elif case == "zero-cycle":
        files[0].rename(files[0].with_name("synthetic-B1-C0.txt"))
    else:
        target = tmp_path / "synthetic-external.txt"
        files[0].rename(target)
        files[0].symlink_to(target)
    assert not folder.refresh(now=0)
    assert not folder.refresh(now=1.1)
    assert folder._ready is None


def test_history_date_sort_new_revision_and_undo_branch():
    from dataclasses import replace
    from datetime import datetime

    analysis = Analysis(open_run(SYNTHETIC_PB))
    book = HistoryBook()
    late = capture(analysis, "standard")
    book.add(late)
    analysis.run.metadata.analysis_start = datetime(2000, 1, 1)
    early = capture(analysis, "standard")
    book.add(early)
    analysis.run.metadata.analysis_start = None
    undated = capture(analysis, "standard")
    book.add(undated)
    assert book.records == (early, late, undated)
    book.exclude(late.key, True, "Synthetic first")
    book.undo()
    book.exclude(early.key, True, "Synthetic replacement")
    assert not book.redo()
    assert not book.excluded(late.key)
    assert book.excluded(early.key)
    # Current parameter version is retained separately from as-acquired metadata.
    original = analysis.initial_reduction_parameters
    analysis.run.reduction_parameters = replace(original, faraday_gains={"Low3": 1.1})
    entry = capture(analysis, "gains").data
    assert entry["calibration"]["parameters"]["faraday_gains"] == {"Low3": 1.1}
    assert entry["calibration"]["acquired"] == original.to_dict()
    assert entry["calibration"]["sha256"] == analysis.run.reduction_parameters.sha256
    assert analysis.initial_reduction_parameters == original
