def specimens(path, run=None):
    run = run or open_run(SYNTHETIC_PB)
    path.mkdir(exist_ok=True)
    files = []
    for row in range(run.n_cycles):
        block = run.block[row]
        cycle = row % run.metadata.cycles_per_block + 1
        name = f"synthetic-B{block}-C{cycle}.txt"
        lines = [
            "Version,synthetic-source-schema",
            "SYNTHETIC",
            "",
            "",
            "",
            'Method,"C:\\Synthetic.RAW\\Synthetic z1 Pb-1"',
            "Acquire Date,Monday 18 July 2011 15:1:16",
            f"Functions,{run.n_functions}",
            "",
            "",
            "",
        ]
        lines += [f'{j + 1},"{f.name}"' for j, f in enumerate(run.functions)]
        lines += ["", "#START"]
        lines += [
            f"{j + 1},value,{float(run.values[row, j])!r}"
            for j in range(run.n_functions)
        ]
        lines += ["#END", ""]
        file = path / name
        file.write_text("\n".join(lines))
        files.append(file)
    return run, files


def settled(folder):
    assert not folder.refresh(now=10)
    assert folder.refresh(now=11.1), folder.notice


def gains_specimen(path, *, aborted=False, invalid=False, newer=False):
    """BIFF8 named references specified by GainsFile.cs:132-278.
    Uses the committed-fixture writer's OLE/BIFF scaffolding, adding BIFF NAMEs.
    """
    spec = importlib.util.spec_from_file_location(
        "synthetic_writer",
        Path(__file__).parents[1] / "scripts/make_synthetic_fixtures.py",
    )
    writer = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(writer)
    ctrl = {
        (0, 0): "ABORTED!" if aborted else "",
        (1, 0): 3,
        (2, 0): 2,
        (3, 0): "Monday 18 July 2011 15:1:16",
        (5, 0): "SYNTHETIC",
        (5, 1): "Low1",
        (5, 2): "High1",
        (6, 1): "-" if newer else "Faraday",
        (6, 2): "Faraday",
        (7, 1): 1,
        (7, 2): 2,
    }
    gains = {
        (1, 1): 1.0,
        (2, 1): -2.0,
        (3, 1): 3.0,
        (1, 2): 4.0,
        (2, 2): "unknown" if invalid else 6.0,
        (3, 2): 8.0,
    }
    bodies = [writer._sheet_stream(ctrl), writer._sheet_stream(gains)]
    rec = writer._record
    head = writer._bof(5) + rec(0x42, struct.pack("<H", 1200))
    head += rec(0x1AE, struct.pack("<HH", 2, 0x401))
    head += rec(
        0x17,
        struct.pack("<H", 2)
        + struct.pack("<HHH", 0, 0, 0)
        + struct.pack("<HHH", 0, 1, 1),
    )
    for name, sheet, row, col in [
        ("ILV_ErrorMessage", 0, 0, 0),
        ("CCG_TotalCycles", 0, 1, 0),
        ("ILV_NoCollectors", 0, 2, 0),
        ("ILV_StartTime", 0, 3, 0),
        ("ILV_CollNames", 0, 5, 0),
        ("CCG_Gains", 1, 1, 0),
    ]:
        formula = b"\x3a" + struct.pack("<HHH", sheet, row, col)
        header = struct.pack(
            "<HBBHHHBBBB", 0, 0, len(name), len(formula), 0, 0, 0, 0, 0, 0
        )
        head += rec(0x18, header + b"\x00" + name.encode() + formula)
    bounds = []
    offset = (
        len(head)
        + sum(4 + 6 + len(writer._unicode(n, "<B")) for n in ("CTRL", "Gains"))
        + 4
    )
    for name, body in zip(("CTRL", "Gains"), bodies):
        bounds.append(
            rec(0x85, struct.pack("<IBB", offset, 0, 0) + writer._unicode(name, "<B"))
        )
        offset += len(body)
    path.write_bytes(
        writer.compound_file(head + b"".join(bounds) + rec(0xA) + b"".join(bodies))
    )
    return path


def standard_specimen(path):
    """StandardsFile.cs:164-201 consumes RawRatio signed cycles and block length."""
    values = b"\x0f" + i(4) + i(4) + b"\x06" + struct.pack("<4d", 1.0, -2.0, 3.0, 5.0)
    ratio = cls(
        3,
        "Tripoli.RawRatio",
        ["Name", "Ratios", "CyclesPerBlock"],
        [1, 2, 0],
        b"\x08",
        string(5, "206/205 D") + values + i(2),
    )
    items = b"\x10" + i(2) + i(1) + ratio
    root = cls(
        1,
        "Tripoli.TripoliWorkProduct",
        ["ArrayList+_items", "ArrayList+_size"],
        [2, 0],
        b"\x08",
        items + i(1),
    )
    path.write_bytes(stream(root))
    return path


def test_history_capture_immutable_versioned_exclusions_and_sorting():
    """OGTripoli/source/TripoliHistoryFolderGains.cs:151-192;
    OGTripoli/source/TripoliHistoryFolderStandards.cs:209-253;
    OGTripoli/source/forms/frmHistoryGraph.cs:408-427.
    Separate immutable revisions and undo are intentional native extensions.
    """
    a = Analysis(open_run(SYNTHETIC_PB))
    before = (
        cycles_csv_text(a),
        a.history,
        a.initial_reduction_parameters.canonical_json(),
    )
    gains, standard = capture(a, "gains"), capture(a, "standard")
    book = HistoryBook()
    assert book.add(gains) and book.add(standard)
    assert not book.add(gains)
    payload = standard.data
    payload["review"]["included"][0][0] = False
    assert standard.data["review"]["included"][0][0]
    a.toggle_cycles([0], keys=[a.keys[0]])
    revision = capture(a, "standard")
    assert revision.key != standard.key
    assert (
        standard.payload
        == capture(Analysis(open_run(SYNTHETIC_PB)), "standard").payload
    )
    assert book.add(revision)
    assert book.exclude(standard.key, True, "Synthetic unstable standard")
    assert book.excluded(standard.key)
    assert book.undo() and not book.excluded(standard.key)
    saved = HistoryBook.from_dict(book.to_dict())
    assert saved.redo() and saved.excluded(standard.key)
    assert saved.exclude(standard.key, False, "Synthetic restored")
    assert not saved.excluded(standard.key)
    assert saved.to_dict()["events"][-1]["reason"] == "Synthetic restored"
    a.undo()
    assert (
        cycles_csv_text(a),
        a.history,
        a.initial_reduction_parameters.canonical_json(),
    ) == before
    assert list(book.records) == sorted(
        book.records,
        key=lambda r: (r.data["date"] is None, r.data["date"] or "", r.key),
    )
    with pytest.raises(ValueError, match="reason"):
        book.exclude(standard.key, True, "")


def test_history_refuses_unknown_schema_hash_and_replay():
    a = Analysis(open_run(SYNTHETIC_U))
    book = HistoryBook()
    entry = capture(a, "standard")
    book.add(entry)
    book.exclude(entry.key, True, "Synthetic reason")
    for field, value in [("version", 2), ("applied", -1)]:
        bad = book.to_dict()
        bad[field] = value
        with pytest.raises(ValueError):
            HistoryBook.from_dict(bad)
    bad = book.to_dict()
    bad["records"][0]["data"]["label"] = "tampered"
    with pytest.raises(ValueError, match="hash"):
        HistoryBook.from_dict(bad)
    bad = book.to_dict()
    bad["events"][0]["before"] = True
    with pytest.raises(ValueError, match="replay"):
        HistoryBook.from_dict(bad)
    bad = book.to_dict()
    bad["extra"] = True
    with pytest.raises(ValueError):
        HistoryBook.from_dict(bad)


def test_gains_source_schema_positive_means_collector_mapping_and_no_correction(
    tmp_path,
):
    """OGTripoli/source/GainsFile.cs:157-278; RawRatio.cs:1164-1252.
    Synthetic BIFF8 only: named ranges, Low/High Faraday, negative→zero/missing.
    No vendor-produced workbook or independent calibrated numeric oracle exists.
    """
    for newer in (False, True):
        path = gains_specimen(tmp_path / "synthetic-gains.xls", newer=newer)
        item = read_gains(path)
        low, high = item.data["series"]
        assert (low["key"], low["mean"], low["n"]) == ("Low1", 2.0, 2)
        assert low["se"] == pytest.approx(1.0)
        assert (high["key"], high["mean"], high["n"]) == ("High1", 6.0, 3)
        assert high["se"] == pytest.approx(2 / np.sqrt(3))
        assert item.data["date"] == "2011-07-18T15:01:16"
        assert (
            item.data["source"]["sha256"]
            == hashlib.sha256(path.read_bytes()).hexdigest()
        )
        assert item.data["calibration"]["collectors"][0]["cycles"] == [1.0, 0.0, 3.0]


