def test_completed_folder_synthetic_replay_to_completed_run(tmp_path):
    """OGTripoli/source/vendors_data/IonVantageLiveDataCyclesFolder.cs:75-216.
    Re-serialize a committed synthetic workbook into source-schema cycle TXT.
    Every representable cycle/function/block, mask, summary equals completed open.
    C# text lacks elapsed times, units and true method name: do not invent them.
    """
    run, files = specimens(tmp_path / "synthetic-folder")
    folder = CompletedFolder(files[0].parent)
    # Replay arrival in two batches. No automatic import/append/rejection.
    removed = [(p, p.read_bytes()) for p in files[run.metadata.cycles_per_block :]]
    for p, data in removed:
        p.unlink()
    assert not folder.refresh(now=0)
    assert folder.refresh(now=1.1)
    first = folder.snapshot_bytes(completed=True)
    for p, data in removed:
        p.write_bytes(data)
    assert not folder.refresh(now=2)
    assert folder.refresh(now=3.1), folder.notice
    final = folder.snapshot_bytes(completed=True)
    assert final != first
    path = tmp_path / "synthetic-completed.json"
    path.write_bytes(final)
    imported = open_run(path)
    np.testing.assert_array_equal(imported.values, run.values)
    np.testing.assert_array_equal(imported.cycle, run.cycle)
    np.testing.assert_array_equal(imported.block, run.block)
    np.testing.assert_array_equal(imported.invalid, run.invalid)
    assert imported.keys == run.keys
    assert np.isnan(imported.time).all()
    assert imported.metadata.complete is None and imported.metadata.method is None
    a, b = Analysis(imported), Analysis(run)
    np.testing.assert_array_equal(a.effective, b.effective)
    assert [a.stats(k).to_dict() for k in a.keys] == [
        b.stats(k).to_dict() for k in b.keys
    ]
    from rawtims.fractions import Fraction

    state = SessionState(fractions=[Fraction(fraction_id="synthetic", pb=a)])
    saved = save_session(state, tmp_path / "synthetic.rawtims")
    loaded, problems = load_session(saved)
    assert not problems
    assert cycles_csv_text(loaded.analyses()[0]) == cycles_csv_text(a)
    assert not a.history


def test_folder_duplicates_conflicts_truncation_gaps_and_changes(tmp_path):
    """C# IonVantageLiveDataCyclesFolder.cs:139-184; conservative missing/duplicate guards are native extensions."""
    _, files = specimens(tmp_path / "synthetic-folder")
    folder = CompletedFolder(files[0].parent)
    with pytest.raises(UnsupportedFile, match="confirmation"):
        folder.snapshot_bytes()
    duplicate = files[0].with_name(files[0].name.replace("-B1-", "-B01-"))
    duplicate.write_bytes(files[0].read_bytes())
    settled(folder)
    assert "1 identical duplicates" in folder.notice
    original = duplicate.read_bytes()
    duplicate.write_bytes(original.replace(b",value,", b",value,9", 1))
    assert not folder.refresh(now=12)
    assert not folder.refresh(now=13.1) and "conflicting duplicate" in folder.notice
    duplicate.unlink()
    original = files[0].read_bytes()
    files[0].write_bytes(original.split(b"#START")[0])
    assert not folder.refresh(now=14)
    assert not folder.refresh(now=15.1) and (
        "#START" in folder.notice or "truncated" in folder.notice
    )
    files[0].write_bytes(original)
    assert not folder.refresh(now=16)
    assert folder.refresh(now=17.1)
    missing = files[1].read_bytes()
    files[1].unlink()
    assert not folder.refresh(now=18) and "missing cycle" in folder.notice
    files[1].write_bytes(missing)
    assert not folder.refresh(now=19)
    assert folder.refresh(now=20.1)
    files[0].write_bytes(original + b"unknown\n")
    with pytest.raises(UnsupportedFile, match="Refresh"):
        folder.snapshot_bytes(completed=True)


